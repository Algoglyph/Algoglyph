import fs from 'node:fs';
import path from 'node:path';

const CONTENT_ROOT = path.resolve('content');
const OUTPUT_FILE = path.resolve('src/generated/articleContent.ts');
const CHECK_ONLY = process.argv.includes('--check');
const contentScope = JSON.parse(fs.readFileSync('src/config/contentScope.json', 'utf8'));
const activeContentTopics = new Set(contentScope.activeContentTopics);
const primaryImageSlugAliases = new Map([
  ['arrays', 'static-arrays'],
  ['bellman-ford', 'bellman-ford-floyd-warshall'],
  ['heap', 'min-heaps'],
  ['linked-list', 'singly-linked-lists'],
  ['queue', 'fifo-queues'],
  ['stack', 'lifo-stacks'],
]);

const toPosix = (value) => value.split(path.sep).join('/');

const topicEntries = fs.readdirSync(CONTENT_ROOT, { withFileTypes: true })
  .filter((entry) => entry.isDirectory() && activeContentTopics.has(entry.name))
  .sort((a, b) => a.name.localeCompare(b.name));

const articles = [];
const seenSlugs = new Set();

for (const topicEntry of topicEntries) {
  const topicPath = path.join(CONTENT_ROOT, topicEntry.name);
  const nestedDirectories = fs.readdirSync(topicPath, { withFileTypes: true })
    .filter((entry) => entry.isDirectory());
  if (nestedDirectories.length > 0) {
    throw new Error(`Article topic folders must not contain subdirectories: content/${topicEntry.name}`);
  }

  const files = fs.readdirSync(topicPath, { withFileTypes: true })
    .filter((entry) => entry.isFile() && entry.name.endsWith('.md'))
    .sort((a, b) => a.name.localeCompare(b.name));

  for (const file of files) {
    const slug = file.name.slice(0, -3);
    if (!/^[a-z0-9]+(?:-[a-z0-9]+)*$/.test(slug)) {
      throw new Error(`Article filename must be a lowercase kebab-case slug: ${file.name}`);
    }
    if (seenSlugs.has(slug)) throw new Error(`Duplicate canonical article slug: ${slug}`);
    seenSlugs.add(slug);

    const absolutePath = path.join(topicPath, file.name);
    const markdown = fs.readFileSync(absolutePath, 'utf8').replace(/\r\n/g, '\n');
    const proseOnly = markdown.replace(/```[\s\S]*?```/g, '');
    const headings = [...proseOnly.matchAll(/^#\s+(.+)$/gm)];
    if (headings.length !== 1) {
      throw new Error(`${toPosix(path.relative(process.cwd(), absolutePath))} must contain exactly one H1`);
    }

    const imageSlug = primaryImageSlugAliases.get(slug) ?? slug;
    const image = ['png', 'jpg']
      .map((extension) => `/images/dsa/${imageSlug}-dark.${extension}`)
      .find((candidate) => fs.existsSync(path.join('public', candidate)));

    articles.push({
      slug,
      topic: topicEntry.name,
      title: headings[0][1].trim(),
      sourcePath: toPosix(path.relative(process.cwd(), absolutePath)),
      markdown,
      image,
    });
  }
}

articles.sort((a, b) => a.slug.localeCompare(b.slug));

const output = [
  '// This file is generated by scripts/generateArticleIndex.mjs.',
  '// Canonical article bodies live only under content/<topic>/<slug>.md.',
  'export interface CanonicalArticle {',
  '  slug: string;',
  '  topic: string;',
  '  title: string;',
  '  sourcePath: string;',
  '  markdown: string;',
  '  image?: string;',
  '}',
  `export const CANONICAL_ARTICLES: readonly CanonicalArticle[] = ${JSON.stringify(articles, null, 2)};`,
  '',
].join('\n');

if (CHECK_ONLY) {
  const existing = fs.existsSync(OUTPUT_FILE) ? fs.readFileSync(OUTPUT_FILE, 'utf8') : '';
  if (existing !== output) {
    throw new Error('src/generated/articleContent.ts is stale. Run npm run content:index.');
  }
  console.log(`Canonical article index is current (${articles.length} articles).`);
} else {
  fs.mkdirSync(path.dirname(OUTPUT_FILE), { recursive: true });
  if (!fs.existsSync(OUTPUT_FILE) || fs.readFileSync(OUTPUT_FILE, 'utf8') !== output) {
    fs.writeFileSync(OUTPUT_FILE, output);
  }
  console.log(`Generated canonical article index with ${articles.length} articles.`);
}
